#!/usr/bin/env python3
"""Dependency licence gate.

    check_lock.py [uv.lock]          fail if the lock names a banned package
    check_lock.py --licenses         also read every installed distribution's
                                     licence metadata and fail on a banned one
    check_lock.py --write-notices    regenerate THIRD_PARTY_NOTICES.md
    check_lock.py --check-notices    fail if THIRD_PARTY_NOTICES.md is stale

The LangGraph server packages are source-available (Elastic-2.0), not open
source; the engine uses only the MIT-licensed LangGraph libraries. AGPL, SSPL
and BUSL are refused too: they would change what a deployment of this
GPL-3.0-only engine must publish.
"""
from __future__ import annotations

import re
import sys
from importlib import metadata
from pathlib import Path

BANNED_PACKAGES = {"langgraph-api", "langgraph-cli", "langgraph-runtime-inmem"}
BANNED_LICENSE = re.compile(r"\b(Elastic|SSPL|Server Side Public|BUSL|Business Source|AGPL|Affero)\b", re.I)


def lock_packages(lock: Path) -> list[str]:
    return re.findall(r'^name = "([^"]+)"$', lock.read_text(), re.M)


def licence_of(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expr = meta.get("License-Expression")
    if expr:
        return expr
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return "; ".join(classifiers)
    text = (meta.get("License") or "").strip()
    return text.splitlines()[0][:80] if text else "UNKNOWN"


NOTICES = Path(__file__).resolve().parents[1] / "THIRD_PARTY_NOTICES.md"
NOTICES_HEAD = """# Third-party notices

ERPClaw is licensed GPL-3.0-only (see LICENSE). It depends on the packages
below, each under its own licence. This file is generated by
`tools/check_lock.py --write-notices` from the installed environment of
`uv sync --locked --all-extras`; CI fails when it is stale. Development-only
packages (test runners) are included.

Data copied from other projects (charts of accounts, tax templates, test
cases) is listed with its source, commit and licence in the section after the
table, once any is copied.

| Package | Version | Licence |
|---|---|---|
"""


def installed_rows() -> list[tuple[str, str, str]]:
    return sorted({(d.metadata["Name"], d.version, licence_of(d)) for d in metadata.distributions()},
                  key=lambda r: r[0].lower())


def render_notices() -> str:
    rows = [r for r in installed_rows() if not r[0].startswith("erpclaw")]
    body = "".join(f"| {n} | {v} | {lic} |\n" for n, v, lic in rows)
    return NOTICES_HEAD + body + "\n## Copied data\n\nNone yet.\n"


def main(argv: list[str]) -> int:
    if "--write-notices" in argv:
        NOTICES.write_text(render_notices())
        print(f"wrote {NOTICES.name}")
        return 0
    if "--check-notices" in argv:
        current = NOTICES.read_text() if NOTICES.exists() else ""
        if current != render_notices():
            print(f"{NOTICES.name} is stale: run tools/check_lock.py --write-notices")
            return 1
        print(f"{NOTICES.name}: current")
        return 0
    lock = Path(next((a for a in argv if not a.startswith("--")), "uv.lock"))
    names = lock_packages(lock)
    bad = sorted(set(names) & BANNED_PACKAGES)
    print(f"{lock}: {len(names)} packages")
    for name in bad:
        print(f"BANNED PACKAGE in lock: {name}")
    failures = len(bad)
    if "--licenses" in argv:
        for name, version, lic in installed_rows():
            flag = ""
            if BANNED_LICENSE.search(lic):
                flag = "  <- BANNED LICENCE"
                failures += 1
            elif lic == "UNKNOWN" and not name.startswith("erpclaw"):
                flag = "  <- unknown, check by hand"
            print(f"{name} {version}: {lic}{flag}")
    print("lock check:", "FAIL" if failures else "ok")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
